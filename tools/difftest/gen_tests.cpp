// Emits one C function per AArch64 encoding using drippu's Translate(), plus the
// generated runtime, for differential testing against a reference CPU.
//
// Usage: gen_tests <encodings.txt> <out_dir> [--fpx] [--simd] [--inline-mem | --direct-mem]
//
// encodings.txt holds one "encoding_hex pc_hex" pair per line. out_dir receives
// tests_<k>.c (2,000 tests each, so they compile in parallel), tests.c (the tables),
// recomp_runtime.h and recomp_runtime.c (and nx_simd.h). --fpx enables drippu's FPX1
// native floating-point fast paths (exact results are still required). --simd first offers
// each FP/SIMD data-processing encoding to the lifter's SIMD emitter (lifter/src/simd.cpp),
// exactly as nxrecomp does; g_test_simd marks the tests it produced. With --fpx too, FADD/FSUB/FMUL/FADDP
// take simd.cpp's FP fast path with drippu's body as the fallback, as nxrecomp emits them. --inline-mem includes nx_mem.h
// (lifter/src/fastmem.cpp: loads and stores inline, as nxrecomp's default), so the tests go through it
// when the harness gives them a page table (dt_set_fastmem). --direct-mem includes the direct form
// (fastmem.cpp DirectHeader: guest memory at a fixed host address, the harness's dt_direct_window).

#include "core/recompiler/arm64_to_c.h"
#include "fastmem.h"
#include "simd.h"

#include <cstdio>
#include <fstream>

int main(int argc, char** argv) {
    bool fpx = false, simd = false, inline_mem = false, direct_mem = false, bad = argc < 3;
    for (int i = 3; i < argc; ++i) {
        const std::string a = argv[i];
        if (a == "--fpx") fpx = true;
        else if (a == "--simd") simd = true;
        else if (a == "--inline-mem") inline_mem = true;
        else if (a == "--direct-mem") direct_mem = true;
        else bad = true;
    }
    if (bad) {
        std::fprintf(stderr, "usage: %s <encodings.txt> <out_dir> [--fpx] [--simd] [--inline-mem | --direct-mem]\n", argv[0]);
        return 2;
    }
    // A standalone recompilation has no JIT to fall back on.
    suyu::recomp::g_translate_all = true;
    suyu::recomp::g_emit_fpx = fpx;
    std::ifstream in(argv[1]);
    std::vector<std::pair<uint32_t, uint64_t>> cases;
    std::string enc, pc;
    while (in >> enc >> pc) {
        cases.emplace_back(static_cast<uint32_t>(std::stoul(enc, nullptr, 16)),
                           std::stoull(pc, nullptr, 16));
    }

    const std::filesystem::path out_dir = argv[2];
    // As nxrecomp writes it (lifter/src/emit.cpp): clang needs <math.h> ahead of drippu's header.
    std::ofstream(out_dir / "recomp_runtime.h") << "#include <math.h>\n" << suyu::recomp::RuntimeH();
    std::ofstream(out_dir / "recomp_runtime.c") << suyu::recomp::RuntimeC();
    std::ofstream(out_dir / "nx_simd.h") << nxrecomp::simd::Header();
    std::ofstream(out_dir / "nx_mem.h") << (direct_mem ? nxrecomp::fastmem::DirectHeader() : nxrecomp::fastmem::Header());

    constexpr size_t kPerFile = 2000;
    const std::string prelude = std::string("/* generated by tools/difftest/gen_tests.cpp */\n#include \"recomp_runtime.h\"\n") +
                                (inline_mem || direct_mem ? "#include \"nx_mem.h\"\n" : "") + "#include \"nx_simd.h\"\n\n";
    std::ofstream part;
    std::string unhandled_flags, terminator_flags, simd_flags, body;
    for (size_t n = 0; n < cases.size(); ++n) {
        if (n % kPerFile == 0) {
            part = std::ofstream(out_dir / ("tests_" + std::to_string(n / kPerFile) + ".c"));
            part << prelude;
        }
        const auto [insn, addr] = cases[n];
        bool miss = false, vector = false;
        body.clear();
        if (simd && ((insn >> 25) & 7) == 7 && nxrecomp::simd::Emit(insn, body)) {
            vector = true;
        } else {
            body.clear();
            suyu::recomp::Translate(insn, addr, body, &miss);
            // nxrecomp's FP fast path (simd.cpp EmitFp), drippu's exact body as its fallback, as the lift
            // calls that body's fp_ helper: with --simd and --fpx
            std::string fast;
            if (simd && fpx && !miss && ((insn >> 25) & 7) == 7 && nxrecomp::simd::EmitFp(insn, body, fast)) {
                body = fast;
                vector = true;
            }
        }
        part << "/* " << std::hex << insn << " @" << addr << std::dec << " */\n"
             << "void t_" << n << "(GuestContext* c) {\n" << body << "}\n";
        unhandled_flags += miss ? "1," : "0,";
        terminator_flags += suyu::recomp::IsTerminator(insn) ? "1," : "0,";
        simd_flags += vector ? "1," : "0,";
    }
    part.close();
    std::ofstream src(out_dir / "tests.c");
    src << prelude;
    for (size_t n = 0; n < cases.size(); ++n) {
        src << "void t_" << n << "(GuestContext* c);\n";
    }
    src << "\ntypedef void (*TestFn)(GuestContext*);\nconst TestFn g_tests[] = {";
    for (size_t n = 0; n < cases.size(); ++n) {
        src << "t_" << n << ",";
    }
    src << "};\nconst unsigned char g_test_unhandled[] = {" << unhandled_flags << "};\n"
        << "const unsigned char g_test_terminator[] = {" << terminator_flags << "};\n"
        << "const unsigned char g_test_simd[] = {" << simd_flags << "};\n"
        << "const int g_test_count = " << cases.size() << ";\n";
    return 0;
}
